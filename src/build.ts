// The pack's files: run.sql with every table in the model's order (inputs
// first), each table's SQL alone in tables/, and a README saying how to run it.
import type { ResolvedModel } from "@ingestron/definitions";
import { tableSql } from "./table-sql.js";

/**
 * run.sql, tables/<schema>.<table>.sql and README.md, or nothing when no table is kept by duckdb-table.
 * @example build(model)["run.sql"]
 */
export function build(model: ResolvedModel): Record<string, string> {
  const tables = model.tables.filter((table) => table.store?.method === "duckdb-table");
  if (tables.length === 0) return {};
  // Resolved types are DuckDB's only when DuckDB provides the defaults.
  const resolvedTypes = model.standard.packs[0]?.startsWith("duckdb@") ?? false;
  const files = Object.fromEntries(
    tables.map((table) => [
      `tables/${table.fullName.schema}.${table.fullName.table}.sql`,
      `${tableSql(model, table, resolvedTypes)}\n`,
    ]),
  );
  const { id, environment } = model.project;
  const header = `-- Generated by Ingestron for ${id} (${environment}): DuckDB SQL. Run it from the project folder.`;
  return {
    ...files,
    "run.sql": `${[header, ...Object.values(files).map((sql) => sql.trimEnd())].join("\n\n")}\n`,
    "README.md": readme(id, environment),
  };
}

function readme(project: string, environment: string): string {
  return `# DuckDB SQL for ${project} (${environment})

Run \`run.sql\` from the project folder, where its paths start, with the DuckDB
command line, naming this folder, for example:

\`\`\`sh
duckdb ingestron.duckdb < build/${environment}/run.sql
\`\`\`

It loads each table into \`ingestron.duckdb\`, runs the transforms, and
publishes each table to the \`published\` folder as \`<schema>.<table>.parquet\`;
the folder must exist. Running it again is safe. \`tables/\` holds each table's
SQL alone, to run one table again:

\`\`\`sh
duckdb ingestron.duckdb -c ".read build/${environment}/tables/<schema>.<table>.sql"
\`\`\`

When the standard lists other packs too, these files are in
\`build/${environment}/duckdb/\` instead.
`;
}
