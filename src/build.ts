// The pack's files: run.sql with every table in the model's order (inputs
// first), each table's SQL alone in tables/, and a README saying how to run it.
import type { ResolvedModel, ResolvedTable } from "@ingestron/definitions";
import { remote } from "./request.js";
import { buildSql, publishSql, tableSql } from "./table-sql.js";

/**
 * run.sql, tables/<schema>.<table>.sql and README.md, or nothing when no table is kept by duckdb-table.
 * run.sql builds every table in one transaction and publishes them only after it commits.
 * @example build(model)["run.sql"]
 */
export function build(model: ResolvedModel): Record<string, string> {
  const tables = model.tables.filter((table) => table.store?.method === "duckdb-table");
  if (tables.length === 0) return {};
  // Resolved types are DuckDB's only when DuckDB provides the defaults.
  const resolvedTypes = model.standard.packs[0]?.startsWith("duckdb@") ?? false;
  const files = Object.fromEntries(
    tables.map((table) => [
      `tables/${table.fullName.schema}.${table.fullName.table}.sql`,
      `${tableSql(model, table, resolvedTypes)}\n`,
    ]),
  );
  const { id, environment } = model.project;
  const header = `-- Generated by Ingestron for ${id} (${environment}): DuckDB SQL. Run it from the project folder.`;
  const builds = tables.map((table) => buildSql(model, table, resolvedTypes).join("\n"));
  const published = ["-- Published only once every table is built.", ...tables.map(publishSql)];
  return {
    ...files,
    "run.sql": `${[header, "BEGIN TRANSACTION;", ...builds, "COMMIT;", published.join("\n")].join("\n\n")}\n`,
    "README.md": readme(model, tables),
  };
}

function readme(model: ResolvedModel, tables: ResolvedTable[]): string {
  const { id, environment } = model.project;
  const folder = `build/${environment}${model.standard.packs.length > 1 ? "/duckdb" : ""}`;
  const inAzure = tables.some(
    (table) => remote(table.store?.output?.location) || remote(table.ingest?.output?.location),
  );
  const job = inAzure
    ? `
In Azure, a Container Apps job runs \`run.sql\` with the public image
\`ghcr.io/ingestron/duckdb-runner:1\`: copy this folder to storage and set the
job's \`INGESTRON_SQL\` to the copied \`run.sql\`. \`ingestron request\` lists
what the job needs.
`
    : "";
  return `# DuckDB SQL for ${id} (${environment})

Run \`run.sql\` from the project folder, where its paths start, with the DuckDB
command line; \`-bail\` stops at the first error:

\`\`\`sh
duckdb -bail ingestron.duckdb -c ".read ${folder}/run.sql"
\`\`\`

It builds every table in \`ingestron.duckdb\` in one transaction, then
publishes each one to the \`published\` folder as \`<schema>.<table>.parquet\`;
the folder must exist. A run that fails publishes nothing new. Running it again
is safe. \`tables/\` holds each table's SQL alone, to run one table again:

\`\`\`sh
duckdb -bail ingestron.duckdb -c ".read ${folder}/tables/<schema>.<table>.sql"
\`\`\`
${job}`;
}
